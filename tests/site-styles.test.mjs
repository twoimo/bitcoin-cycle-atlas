import assert from 'node:assert/strict';
import test from 'node:test';
import {mkdtemp, mkdir, readFile, writeFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {SITE_STYLE_GROUPS, SITE_STYLE_SOURCES, buildSiteStyles, siteStyleBundleContents,
  siteStylesheetEntries, inlineSiteStyles, checkCombinableStyle} from '../scripts/build-site-styles.mjs';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));
const html = await readFile(resolve(dist, 'index.html'), 'utf8');

test('four root requests retain every source sheet in its original cascade position', async () => {
  assert.equal(SITE_STYLE_SOURCES.length, 42);
  assert.equal(new Set(SITE_STYLE_SOURCES).size, 42, 'no source is duplicated');
  const entries = siteStylesheetEntries(html);
  assert.deepEqual(entries.map(entry => entry.file), ['styles.css','site-before-shell.css','atlas-shell.css','site-after-shell.css']);
  assert.equal(entries[1].sources[0], 'compact.css');
  assert.equal(entries[1].sources.at(-1), 'market-lab.css');
  assert.equal(entries[3].sources[0], 'compact-toolbar.css');
  assert.equal(entries[3].sources.at(-2), 'ui/quote-hud.css', 'all prior sources retain their original order');
  assert.equal(entries[3].sources.at(-1), 'ui/shell-layout.css', 'P1 shell is appended after the existing cascade');
  const generated = await buildSiteStyles(dist, {check:true});
  assert.equal(generated.files.length, 2);
  for (const file of generated.files) {
    const href = entries.find(entry => entry.file === file.file).tag.match(/href="([^"]+)"/)[1];
    assert.equal(new URL(href, 'https://atlas.invalid/').searchParams.get('v'), file.sha256.slice(0, 12),
      `${file.file} must invalidate its URL when the generated bytes change`);
  }
  for (const group of SITE_STYLE_GROUPS.filter(group => group.sources.length > 1)) {
    const bundled = await readFile(resolve(dist, group.file), 'utf8');
    let cursor = 0;
    for (const file of group.sources) {
      const source = await readFile(resolve(dist, file), 'utf8');
      const marker = bundled.indexOf(`/* Source: ${file}; SHA-256: `, cursor);
      assert.ok(marker >= cursor, `${file} retains cascade order`);
      const start = bundled.indexOf(' */\n', marker) + ' */\n'.length;
      assert.equal(bundled.slice(start, start + source.length), source, `${file} retains exact authored CSS`);
      cursor = start + source.length;
    }
  }
});

test('offline packaging expands the request bundles into all 42 exact source blocks', async () => {
  const inlined = await inlineSiteStyles(html, dist);
  let previous = -1;
  for (const file of SITE_STYLE_SOURCES) {
    const block = `<style>\n${await readFile(resolve(dist, file), 'utf8')}\n</style>`;
    assert.equal(inlined.split(block).length - 1, 1, file);
    const position = inlined.indexOf(block);
    assert.ok(position > previous, `${file} retains offline cascade order`);
    previous = position;
  }
  assert.equal([...inlined.matchAll(/<style>/g)].length, 42);
  assert.doesNotMatch(inlined, /<link rel="stylesheet" href="\.\//);
});

test('missing, repeated, extra and reordered physical links fail instead of dropping source styles', () => {
  const entries = siteStylesheetEntries(html);
  for (const changed of [html.replace(entries[1].tag, ''), html.replace(entries[1].tag, entries[1].tag + entries[1].tag),
    html.replace(entries[0].tag, '<link rel="stylesheet" href="./extra.css">' + entries[0].tag),
    html.replace(entries[1].tag, 'SWAP').replace(entries[2].tag, entries[1].tag).replace('SWAP', entries[2].tag)]) {
    assert.throws(() => siteStylesheetEntries(changed), /complete base\/before-shell\/shell\/after-shell cascade/);
  }
});

test('URL and sheet-scoped directives require an explicit policy before concatenation', () => {
  for (const source of ['@import "more.css";', '@charset "utf-8";', '@namespace svg "http://www.w3.org/2000/svg";',
    '.image { background: url(../image.png) }', '.icon { mask: URL("data:image/svg+xml,x") }']) {
    assert.throws(() => checkCombinableStyle(source, 'fixture.css'), /explicit bundling policy: fixture\.css/);
  }
  assert.doesNotThrow(() => checkCombinableStyle('/* @import url(example.css) documents a rejected pattern */\n.x { width:72px }', 'fixture.css'));
});

test('generation is reproducible and stale or absent generated bytes are rejected', async t => {
  const fixture = await mkdtemp(resolve(tmpdir(), 'atlas-site-styles-'));
  t.after(() => rm(fixture, {recursive:true,force:true}));
  for (const [index, file] of SITE_STYLE_SOURCES.entries()) {
    await mkdir(dirname(resolve(fixture, file)), {recursive:true});
    await writeFile(resolve(fixture, file), `.source-${index} { --value: ${index}px; }\n`);
  }
  await assert.rejects(buildSiteStyles(fixture, {check:true}), /Missing generated stylesheet/);
  const first = await buildSiteStyles(fixture);
  const second = await buildSiteStyles(fixture);
  assert.deepEqual(second, first);
  assert.deepEqual((await buildSiteStyles(fixture, {check:true})).files, first.files);
  const bundle = await siteStyleBundleContents(fixture);
  assert.equal(bundle.size, 2);
  await writeFile(resolve(fixture, 'compact.css'), '.changed { min-height: 44px; }\n');
  await assert.rejects(buildSiteStyles(fixture, {check:true}), /Stale generated stylesheet: site-before-shell\.css/);
  await buildSiteStyles(fixture);
  await writeFile(resolve(fixture, 'ui/quote-hud.css'), '@import "hidden-network.css";');
  await assert.rejects(buildSiteStyles(fixture), /explicit bundling policy: ui\/quote-hud\.css/);
});
