#!/usr/bin/env node
// Discover the conference boot graph without evaluating or rewriting modules.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {lstat, mkdir, readFile, realpath, writeFile} from 'node:fs/promises';
import {dirname, resolve, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {javascriptModuleSpecifiers} from './module-references.mjs';

const webRoot = new URL('https://atlas.invalid/bitcoin-cycle-atlas/');
const generatorPath = 'scripts/build-site-preloads.mjs';
const manifestPath = 'docs/conference/boot-preload-graph.json';
const scriptPattern = /<script id="atlas-boot-preloads">[\s\S]*?<\/script>/g;
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const scriptJson = value => JSON.stringify(value).replaceAll('<', '\\u003c');

function moduleUrl(specifier, parent = './') {
  assert.match(specifier, /^\.\.?\//, `Preload graph requires a relative URL: ${specifier}`);
  const url = new URL(specifier, new URL(parent, webRoot));
  assert.ok(url.origin === webRoot.origin && url.pathname.startsWith(webRoot.pathname),
    `Preload URL escapes the site root: ${specifier}`);
  return './' + url.pathname.slice(webRoot.pathname.length) + url.search + url.hash;
}

async function readSource(dist, url) {
  const file = decodeURIComponent(new URL(url, webRoot).pathname.slice(webRoot.pathname.length));
  const path = resolve(dist, file), root = resolve(dist);
  assert.ok(path.startsWith(root + sep), `Preload source escapes dist: ${file}`);
  assert.ok((await lstat(path)).isFile(), `Preload source must be a regular file: ${file}`);
  assert.ok((await realpath(path)).startsWith((await realpath(root)) + sep),
    `Preload source resolves outside dist: ${file}`);
  const bytes = await readFile(path);
  return {file, bytes:bytes.length, sha256:sha256(bytes), source:bytes.toString('utf8')};
}

export async function collectStaticModuleGraph(dist, roots) {
  const queued = new Set(), queue = [], modules = [];
  const add = (url, depth) => {
    if (!queued.has(url)) { queued.add(url); queue.push({url, depth}); }
  };
  for (const root of roots) add(moduleUrl(root), 0);
  // Breadth-first traversal follows the root order, then source import order.
  // Full URLs retain query/fragment module identity; cycles terminate normally.
  for (const {url, depth} of queue) {
    const {source, ...file} = await readSource(dist, url);
    const imports = javascriptModuleSpecifiers(source, {includeDynamic:false})
      .map(specifier => ({specifier, url:moduleUrl(specifier, url)}));
    modules.push({url, ...file, depth, imports});
    for (const dependency of imports) add(dependency.url, depth + 1);
  }
  return modules;
}

function referencedModule(source, parent, expectedFile, {includeDynamic = true} = {}) {
  const urls = [...new Set(javascriptModuleSpecifiers(source, {includeDynamic})
    .map(specifier => moduleUrl(specifier, parent))
    .filter(url => new URL(url, webRoot).pathname === webRoot.pathname + expectedFile))];
  assert.equal(urls.length, 1, `Expected one reference to ${expectedFile} from ${parent}`);
  return urls[0];
}

function renderPreloads(manifest, manifestSha256) {
  const urls = manifest.modulePreloads.map(url => '        ' + scriptJson(url)).join(',\n');
  return `<script id="atlas-boot-preloads">
    // Generated by ${generatorPath}; graph/source SHA-256: ${manifestSha256}.
    (() => {
      if (new URLSearchParams(location.search).get('page') !== 'conference') return;
      // This existing head link is already parsed and is rebased by build-pages.
      // Module evaluation and readiness still belong to the original entry.
      const entryUrl = document.querySelector('link[rel="modulepreload"]').href;
      const timeline = document.createElement('link');
      timeline.rel = 'preload';
      timeline.as = 'fetch';
      timeline.crossOrigin = 'anonymous';
      timeline.fetchPriority = 'high';
      timeline.href = new URL(${scriptJson(manifest.timeline.url)}, entryUrl).href;
      // Reserve the data request before enqueueing the module hints.
      document.head.append(timeline);
      for (const href of [
${urls}
      ]) {
        const link = document.createElement('link');
        link.rel = 'modulepreload';
        link.href = new URL(href, entryUrl).href;
        document.head.append(link);
      }
    })();
  </script>`;
}

export async function createSitePreloads(root) {
  const dist = resolve(root, 'dist'), index = await readFile(resolve(dist, 'index.html'), 'utf8');
  const scripts = [...index.matchAll(scriptPattern)];
  assert.equal(scripts.length, 1, 'Expected one conference preload script');
  const entries = [...index.matchAll(/<script type="module" src="([^"]+)"><\/script>/g)];
  assert.equal(entries.length, 1, 'Expected one module entry');
  const entry = moduleUrl(entries[0][1].replaceAll('&amp;', '&'));
  const shared = [...index.matchAll(/<link rel="modulepreload" href="([^"]+)">/g)];
  assert.equal(shared.length, 1, 'Other routes retain exactly their existing shared entry hint');
  assert.equal(moduleUrl(shared[0][1].replaceAll('&amp;', '&')), entry, 'Shared hint must match the entry URL');
  assert.ok(shared[0].index < scripts[0].index, 'The entry URL must be available during head parsing');
  assert.ok(scripts[0].index < index.indexOf('<link rel="stylesheet" href="./styles.css'),
    'Conference hints must precede the blocking CSS');

  const entrySource = await readSource(dist, entry);
  const app = referencedModule(entrySource.source, entry, 'app.js');
  const appSource = await readSource(dist, app);
  const route = referencedModule(appSource.source, app, 'conference/route.js', {includeDynamic:false});
  const routeSource = await readSource(dist, route);
  const player = referencedModule(routeSource.source, route, 'conference/player.js');
  const roots = [entry, app, player];
  const modules = await collectStaticModuleGraph(dist, roots);
  const playerModule = modules.find(module => module.url === player);
  const timelineModule = referencedModule((await readSource(dist, player)).source,
    player, 'conference/timeline.js', {includeDynamic:false});
  assert.ok(playerModule.imports.some(dependency => dependency.url === timelineModule));
  const timeline = await readSource(dist, './conference/timeline.json');
  // A malformed input cannot be scheduled as if it were the committed dataset.
  JSON.parse(timeline.source);
  const modulePreloads = [timelineModule, ...modules.map(module => module.url)
    .filter(url => url !== entry && url !== timelineModule)];
  const manifest = {
    schemaVersion:1, kind:'atlas-conference-boot-preloads', route:'conference',
    generator:{file:generatorPath, sha256:sha256(await readFile(fileURLToPath(import.meta.url)))},
    roots, sharedModulePreload:entry, modules,
    timeline:{url:'./conference/timeline.json', file:timeline.file, bytes:timeline.bytes,
      sha256:timeline.sha256, rel:'preload', as:'fetch', crossorigin:'anonymous', fetchpriority:'high'},
    modulePreloads,
    summary:{moduleUrls:modules.length, uniqueModuleFiles:new Set(modules.map(module => module.file)).size,
      conferenceModulePreloads:modulePreloads.length, sharedModulePreloads:1,
      staticImportEdges:modules.reduce((sum, module) => sum + module.imports.length, 0),
      maxShortestImportDepth:Math.max(...modules.map(module => module.depth)),
      moduleBytesByUrl:modules.reduce((sum, module) => sum + module.bytes, 0)},
  };
  const manifestBytes = JSON.stringify(manifest, null, 2) + '\n';
  const script = renderPreloads(manifest, sha256(manifestBytes));
  const html = index.slice(0, scripts[0].index) + script + index.slice(scripts[0].index + scripts[0][0].length);
  return {html, manifest, manifestBytes, script};
}

export async function buildSitePreloads(root, {check = false} = {}) {
  const generated = await createSitePreloads(root);
  const outputs = [['dist/index.html', generated.html], [manifestPath, generated.manifestBytes]];
  for (const [file, source] of outputs) {
    const path = resolve(root, file);
    if (check) {
      const current = await readFile(path, 'utf8').catch(error => {
        if (error.code === 'ENOENT') throw new Error(`Missing generated preload output: ${file}`);
        throw error;
      });
      assert.ok(current === source, `Stale generated preload output: ${file}; run node ${generatorPath}`);
    } else {
      await mkdir(dirname(path), {recursive:true});
      await writeFile(path, source);
    }
  }
  return {status:'ok', mode:check ? 'check' : 'write', ...generated.manifest.summary,
    timeline:generated.manifest.timeline, manifestSha256:sha256(generated.manifestBytes)};
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  assert.ok(args.length === 0 || (args.length === 1 && args[0] === '--check'),
    `Usage: node ${generatorPath} [--check]`);
  console.log(JSON.stringify(await buildSitePreloads(fileURLToPath(new URL('../', import.meta.url)),
    {check:args.includes('--check')})));
}
