#!/usr/bin/env node
// Reduce request count without changing the authored cascade or source sheets.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const beforeShell = Object.freeze([
  'compact.css', 'outlook.css', 'lab.css', 'atlas.css', 'viewport.css',
  'chart-details-panel.css', 'analysis-dock.css', 'chart-magnet.css',
  'mobile-workspace.css', 'workspace-tools.css', 'chart-workspace-controls.css',
  'research-annotations.css', 'chart-export-workbench.css', 'cycle-milestones.css',
  'compact-chart-layout.css', 'chart-bottom-bar.css', 'symbol-selector.css',
  'eth-view.css', 'equity-view.css', 'research-reader.css', 'ethereum-history.css',
  'daily-data.css', 'forecast-journal.css', 'chart-replay.css', 'monthly-backtest.css',
  'ipo-view.css', 'market-lab.css',
]);
const afterShell = Object.freeze([
  'compact-toolbar.css', 'ui/rsi-simulation.css', 'legacy-workspace-toolbar.css',
  'vendor/skullet/styles.css', 'loading-surfaces.css', 'editorial-system.css',
  'editorial-panels.css', 'editorial-ledgers.css', 'relay-room.css',
  'conference/player.css', 'ui/chart-legend.css', 'ui/quote-hud.css', 'ui/shell-layout.css',
]);
// Keep the base and shell as direct links. Their relative order is also an
// existing 44px touch-floor contract; both intervening ranges stay in order.
export const SITE_STYLE_GROUPS = Object.freeze([
  Object.freeze({file:'styles.css', sources:Object.freeze(['styles.css'])}),
  Object.freeze({file:'site-before-shell.css', sources:beforeShell}),
  Object.freeze({file:'atlas-shell.css', sources:Object.freeze(['atlas-shell.css'])}),
  Object.freeze({file:'site-after-shell.css', sources:afterShell}),
]);
export const SITE_STYLE_SOURCES = Object.freeze(SITE_STYLE_GROUPS.flatMap(group => group.sources));
const sha256 = source => createHash('sha256').update(source).digest('hex');

export function checkCombinableStyle(source, file) {
  // No URL rebasing or at-rule relocation is implicit. A future source using
  // these constructs needs an explicit policy before it can enter a bundle.
  const css = source.replace(/\/\*[\s\S]*?\*\//g, '');
  assert.doesNotMatch(css, /@(?:import|charset|namespace)\b|\burl\s*\(/i,
    `Stylesheet needs explicit bundling policy: ${file}`);
}

export async function siteStyleBundleContents(dist) {
  const result = new Map();
  for (const group of SITE_STYLE_GROUPS.filter(group => group.sources.length > 1)) {
    const sections = [];
    for (const file of group.sources) {
      const source = await readFile(resolve(dist, file), 'utf8');
      checkCombinableStyle(source, file);
      sections.push(`/* Source: ${file}; SHA-256: ${sha256(source)} */\n${source}\n`);
    }
    result.set(group.file, '/* Generated by scripts/build-site-styles.mjs. Edit the source stylesheets; preserve their order. */\n'
      + sections.join('\n'));
  }
  return result;
}

export async function buildSiteStyles(dist, {check = false} = {}) {
  const contents = await siteStyleBundleContents(dist);
  for (const [file, source] of contents) {
    if (check) {
      const committed = await readFile(resolve(dist, file), 'utf8').catch(error => {
        if (error.code === 'ENOENT') throw new Error(`Missing generated stylesheet: ${file}`);
        throw error;
      });
      assert.ok(committed === source, `Stale generated stylesheet: ${file}; run node scripts/build-site-styles.mjs`);
    } else await writeFile(resolve(dist, file), source);
  }
  return {status:'ok', mode:check ? 'check' : 'write', sourceStylesheets:SITE_STYLE_SOURCES.length,
    files:[...contents].map(([file, source]) => ({file, bytes:Buffer.byteLength(source), sha256:sha256(source)}))};
}

export function siteStylesheetEntries(html) {
  const entries = [...html.matchAll(/<link rel="stylesheet" href="\.\/([^"?]+)(?:\?[^"\s]*)?">/g)]
    .map(match => ({tag:match[0], file:match[1]}));
  assert.deepEqual(entries.map(entry => entry.file), SITE_STYLE_GROUPS.map(group => group.file),
    'Root stylesheet links must preserve the complete base/before-shell/shell/after-shell cascade');
  return entries.map((entry, index) => ({...entry, sources:SITE_STYLE_GROUPS[index].sources}));
}

export async function inlineSiteStyles(html, dist) {
  await buildSiteStyles(dist, {check:true});
  for (const entry of siteStylesheetEntries(html)) {
    const blocks = await Promise.all(entry.sources.map(async file => `<style>\n${await readFile(resolve(dist, file), 'utf8')}\n</style>`));
    // The offline document retains all 41 original, exact source style blocks.
    // A replacement callback preserves literal replacement-token bytes in CSS.
    html = html.replace(entry.tag, () => blocks.join('\n'));
  }
  return html;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  assert.ok(args.length === 0 || (args.length === 1 && args[0] === '--check'),
    'Usage: node scripts/build-site-styles.mjs [--check]');
  const dist = fileURLToPath(new URL('../dist/', import.meta.url));
  console.log(JSON.stringify(await buildSiteStyles(dist, {check:args.includes('--check')})));
}
